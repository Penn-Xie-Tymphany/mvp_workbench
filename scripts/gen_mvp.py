def write_nav_table(scan: ProjectScan, dest: Path) -> None:
    decls = []
    entries = []
    for s in scan.screens:
        decls.append(
            f"""
static lv_obj_t ** mvp_root_{s}(void) {{ return &aidogui_ui.{s}.root; }}
static void mvp_zero_{s}(void) {{
    fprintf(stderr, "[probe] zero_handles({s})\\n");
    fflush(stderr);
    memset(&aidogui_ui.{s}, 0, sizeof(aidogui_ui.{s}));
}}""".rstrip()
        )
        entries.append(
            f"    {{ {screen_enum(s)}, ui_{s}_screen_init, ui_{s}_screen_destroy, "
            f"mvp_root_{s}, mvp_zero_{s} }}"
        )
    includes = "\n".join(f'#include "screens/ui_{s}.h"' for s in scan.screens)
    dest.write_text(
        f"""{GEN_BANNER}
#include "mvp_types.h"
#include "ui.h"
#include <stdio.h>
#include <string.h>
{includes}

{chr(10).join(decls)}

const mvp_screen_desc_t mvp_screens[] = {{
{chr(10).join(e + ',' for e in entries)}
}};

const int mvp_screen_count = (int)(sizeof(mvp_screens) / sizeof(mvp_screens[0]));
const app_screen_id_t mvp_bootstrap_screen = {screen_enum(scan.bootstrap)};
""",
        encoding="utf-8",
    )


def write_edges(scan: ProjectScan, dest: Path) -> None:
    rows = []
    for e in scan.edges:
        pkey = f'"{e.param_key}"' if e.param_key else "NULL"
        pval = f'"{e.param_val}"' if e.param_val else "NULL"
        rows.append(
            f"    {{ {screen_enum(e.from_screen)}, {cmd_enum(e.cmd)}, "
            f"{screen_enum(e.to_screen)}, NAV_UNLOAD_{e.policy}, {pkey}, {pval} }}"
        )
    body = ",\n".join(rows) if rows else "    /* no edges discovered */"
    dest.write_text(
        f"""{GEN_BANNER}
#include "mvp_types.h"

const mvp_edge_t mvp_edges[] = {{
{body}
}};

const int mvp_edge_count = (int)(sizeof(mvp_edges) / sizeof(mvp_edges[0]));
""",
        encoding="utf-8",
    )


def write_view_bind(scan: ProjectScan, dest: Path) -> None:
    blocks = []
    by_screen: dict[str, list[Bind]] = {}
    for b in scan.binds:
        by_screen.setdefault(b.screen, []).append(b)
    for s in scan.screens:
        bs = by_screen.get(s, [])
        if not bs:
            continue
        lines = [f"    if (ui->{s}.root && lv_obj_is_valid(ui->{s}.root)) {{"]
        for b in bs:
            lines.append(
                f"        mvp_bind_btn(ui->{s}.{b.btn}, {cmd_enum(b.cmd)});"
            )
        lines.append("    }")
        blocks.append("\n".join(lines))
    dest.write_text(
        f"""{GEN_BANNER}
#include "view_bind.h"
#include "mvp_view.h"
#include "ui.h"

void view_bind(aidogui_ui_t * ui)
{{
    if (!ui) return;
    mvp_view_set_ui(ui);
    mvp_bound_reset();
{chr(10).join(blocks) if blocks else "    (void)ui;"}
    mvp_finish_binds(ui);
}}
""",
        encoding="utf-8",
    )


