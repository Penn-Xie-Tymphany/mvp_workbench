def write_app_model_user_h(dest: Path, fields: list[dict]) -> None:
    """Managed IO_GEN section inside app_model_user.h (included inside
    app_model_t). Everything outside the markers is user content — kept."""
    def decl(f: dict) -> str:
        if f.get("keyed"):
            return None  # keyed fields live in the generated io_store, not here
        if f["ctype"] == "string":
            return f"    char {f['name']}[64]; /* io: {f['rw']} */"
        return f"    {f['ctype']} {f['name']}; /* io: {f['rw']} */"
    decls = "\n".join(decl(f) for f in fields if not f.get("keyed"))
    old = dest.read_text(encoding="utf-8", errors="replace") if dest.is_file() else ""
    if IO_GEN_BEGIN in old and IO_GEN_END in old:
        pre, rest = old.split(IO_GEN_BEGIN, 1)
        _, post = rest.split(IO_GEN_END, 1)
        dest.write_text(
            pre + IO_GEN_BEGIN + "\n" + decls + "\n" + IO_GEN_END + post,
            encoding="utf-8",
        )
    else:
        head = old.rstrip("\n") + "\n\n" if old.strip() else ""
        dest.write_text(head + f"{IO_GEN_BEGIN}\n{decls}\n{IO_GEN_END}\n", encoding="utf-8")


def write_app_io_table(mvp: Path, fields: list[dict]) -> None:
    """Generated name→model-field access table (C has no reflection; the
    sim host protocol uses this to SET/GET fields by name)."""
    kind_map = {"int": "APP_IO_INT", "float": "APP_IO_FLOAT",
                "double": "APP_IO_FLOAT", "bool": "APP_IO_BOOL",
                "string": "APP_IO_STR"}

    def ent_row(f: dict) -> str:
        keyed = f'"{f["keyed"]}"' if f.get("keyed") else "NULL"
        is_str = f["ctype"] == "string" or f.get("keyed")
        off = f'offsetof(app_model_t, {f["name"]})' if not f.get("keyed") else "0"
        return (f'    {{ "{f["name"]}", {kind_map.get(f["ctype"], "APP_IO_FLOAT")}, '
                f'{off}, (double){f.get("init", 0) or 0}, '
                f'{"64" if is_str else "0"}, {keyed} }},')

    entries = "\n".join(ent_row(f) for f in fields)
    (mvp / "app_io_table.h").write_text(
        f"""{GEN_BANNER}
#ifndef APP_IO_TABLE_H
#define APP_IO_TABLE_H

#include <stdbool.h>
#include <stddef.h>

#ifdef __cplusplus
extern "C" {{
#endif

int app_io_count(void);
const char * app_io_name(int idx);
bool app_io_get(int idx, double * out);
bool app_io_set(int idx, double v);
bool app_io_set_name(const char * name, double v);
bool app_io_set_str_name(const char * name, const char * s);
bool app_io_is_str(int idx);
const char * app_io_str(int idx);
void app_io_init(void);

#ifdef __cplusplus
}}
#endif
#endif
""",
        encoding="utf-8",
    )
    (mvp / "app_io_table.c").write_text(
        f"""{GEN_BANNER}
#include "app_io_table.h"
#include "app_model.h"
#include "io_store.h"

#include <stddef.h>
#include <stdio.h>
#include <string.h>

enum {{ APP_IO_INT, APP_IO_FLOAT, APP_IO_BOOL, APP_IO_STR }};

typedef struct {{
    const char * name;
    int kind;
    size_t off;
    double defv;
    size_t cap;
    const char * keyed; /* non-NULL: data lives in io_store keyed by this param */
}} app_io_ent_t;

static const app_io_ent_t g_io_table[] = {{
{entries}
}};

/* current value of a string param field (e.g. m->device) */
static const char * model_str(const char * name)
{{
    for (int i = 0; i < app_io_count(); ++i) {{
        if (g_io_table[i].keyed == NULL && g_io_table[i].kind == APP_IO_STR &&
            strcmp(g_io_table[i].name, name) == 0) {{
            return (const char *)((const char *)app_model_get() + g_io_table[i].off);
        }}
    }}
    return "";
}}

void app_io_init(void)
{{
    for (int i = 0; i < app_io_count(); ++i) app_io_set(i, g_io_table[i].defv);
}}

int app_io_count(void)
{{
    return (int)(sizeof(g_io_table) / sizeof(g_io_table[0]));
}}

const char * app_io_name(int idx)
{{
    if (idx < 0 || idx >= app_io_count()) return NULL;
    return g_io_table[idx].name;
}}

bool app_io_get(int idx, double * out)
{{
    if (idx < 0 || idx >= app_io_count() || !out) return false;
    const app_io_ent_t * e = &g_io_table[idx];
    const char * base = (const char *)app_model_get();
    switch (e->kind) {{
    case APP_IO_INT:   *out = (double)(*(const int *)(base + e->off)); break;
    case APP_IO_FLOAT: *out = (double)(*(const float *)(base + e->off)); break;
    case APP_IO_BOOL:  *out = (*(const bool *)(base + e->off)) ? 1.0 : 0.0; break;
    default: return false;
    }}
    return true;
}}

bool app_io_set(int idx, double v)
{{
    if (idx < 0 || idx >= app_io_count()) return false;
    const app_io_ent_t * e = &g_io_table[idx];
    char * base = (char *)app_model_get();
    switch (e->kind) {{
    case APP_IO_INT:   *(int *)(base + e->off) = (int)v; break;
    case APP_IO_FLOAT: *(float *)(base + e->off) = (float)v; break;
    case APP_IO_BOOL:  *(bool *)(base + e->off) = (v != 0.0); break;
    default: return false;
    }}
    return true;
}}

bool app_io_set_name(const char * name, double v)
{{
    if (!name) return false;
    for (int i = 0; i < app_io_count(); ++i) {{
        if (strcmp(g_io_table[i].name, name) == 0) return app_io_set(i, v);
    }}
    return false;
}}

bool app_io_is_str(int idx)
{{
    if (idx < 0 || idx >= app_io_count()) return false;
    return g_io_table[idx].kind == APP_IO_STR;
}}

const char * app_io_str(int idx)
{{
    if (idx < 0 || idx >= app_io_count() || g_io_table[idx].kind != APP_IO_STR) return NULL;
    if (g_io_table[idx].keyed) {{
        return io_store_get(g_io_table[idx].name, model_str(g_io_table[idx].keyed));
    }}
    return (const char *)((const char *)app_model_get() + g_io_table[idx].off);
}}

bool app_io_set_str(int idx, const char * s)
{{
    if (idx < 0 || idx >= app_io_count() || g_io_table[idx].kind != APP_IO_STR) return false;
    if (g_io_table[idx].keyed) {{
        /* no @key → write the CURRENT navigation param's slot */
        io_store_put(g_io_table[idx].name, model_str(g_io_table[idx].keyed), s ? s : "");
        return true;
    }}
    char * dst = (char *)app_model_get() + g_io_table[idx].off;
    size_t cap = g_io_table[idx].cap;
    if (!cap) return false;
    snprintf(dst, cap, "%s", s ? s : "");
    return true;
}}

bool app_io_set_str_name(const char * name, const char * s)
{{
    if (!name || !name[0]) return false;
    /* "field@key" → explicit keyed slot (e.g. SET rssi@A "..." feeds device A) */
    const char * at = strchr(name, '@');
    if (at && at != name) {{
        char field[24];
        size_t flen = (size_t)(at - name);
        if (flen >= sizeof(field)) return false;
        memcpy(field, name, flen);
        field[flen] = 0;
        for (int i = 0; i < app_io_count(); ++i) {{
            if (g_io_table[i].keyed && strcmp(g_io_table[i].name, field) == 0) {{
                io_store_put(field, at + 1, s ? s : "");
                return true;
            }}
        }}
        return false;
    }}
    for (int i = 0; i < app_io_count(); ++i) {{
        if (strcmp(g_io_table[i].name, name) == 0) return app_io_set_str(i, s);
    }}
    return false;
}}
""",
        encoding="utf-8",
    )


def resolve_btn_field(btn_field: str, available: set[str]) -> str | None:
    """Map a handler-derived button name to the REAL widget field in the
    screen's objects struct. AIDOGUI may name buttons without the btn_
    prefix (WATCH: button_top / watch_digital); fall back to the screen
    root when the clickable is the whole screen."""
    if btn_field in available:
        return btn_field
    stem = btn_field[4:] if btn_field.startswith("btn_") else btn_field
    for cand in (stem, "btn_" + stem):
        if cand in available:
            return cand
    if stem:
        for w in available:
            if stem in w:
                return w
    if "root" in available:
        return "root"
    return None


def scan_project(proj: Path) -> ProjectScan:
    name = proj.name
    screens, bootstrap = scan_screens(proj / "ui.h", proj / "screens")
    buttons = scan_buttons(proj / "aidogui_objects.h", screens)
    widgets = scan_widgets(proj / "aidogui_objects.h", screens)
    widget_info = scan_widget_info(proj, screens)
    edges, binds = scan_edges(proj / "events", screens)
    # Filter edges/binds to known screens
    screen_set = set(screens)
    edges = [e for e in edges if e.from_screen in screen_set and e.to_screen in screen_set]
    binds = [b for b in binds if b.screen in screen_set]
    # Normalize btn fields against the REAL objects struct
    wset = {s: set(ws) | {"root"} for s, ws in widgets.items()}
    fixed_binds: list[Bind] = []
    btn_map: dict[tuple[str, str], str] = {}
    for b in binds:
        real = resolve_btn_field(b.btn, wset.get(b.screen, set()))
        if real is None:
            print(f"[gen_mvp] WARN: no widget for bind {b.screen}.{b.btn} — skipped "
                  "(cmd still dispatchable via sim/test)")
            continue
        btn_map[(b.screen, b.cmd)] = real
        fixed_binds.append(Bind(screen=b.screen, btn=real, cmd=b.cmd))
    for e in edges:
        e.btn = btn_map.get((e.from_screen, e.cmd), e.btn)
    binds = fixed_binds
    cmds = collect_cmds(edges, binds)
    if not bootstrap and screens:
        bootstrap = screens[0]
    scan = ProjectScan(
        name=name,
        screens=screens,
        bootstrap=bootstrap,
        buttons=buttons,
        widgets=widgets,
        widget_info=widget_info,
        edges=edges,
        binds=binds,
        cmds=cmds,
    )
    return scan


