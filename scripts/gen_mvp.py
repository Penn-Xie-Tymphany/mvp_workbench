def scan_edges(events_dir: Path, screens: list[str]) -> tuple[list[Edge], list[Bind]]:
    edges: list[Edge] = []
    binds: list[Bind] = []
    seen_edge: set[tuple[str, str, str]] = set()
    seen_bind: set[tuple[str, str, str]] = set()

    if not events_dir.is_dir():
        return edges, binds

    for path in sorted(events_dir.glob("aido_event_*.c")):
        # aido_event_menu.c → menu
        stem = path.stem  # aido_event_menu
        if not stem.startswith("aido_event_"):
            continue
        from_screen = stem[len("aido_event_") :]
        text = path.read_text(encoding="utf-8", errors="replace")
        # registration map: handler function → the REAL widget it is attached to
        # (lv_obj_add_event_cb(ui->scr.widget, handler, LV_EVENT_*, ...))
        reg_map = {}
        for rm in re.finditer(
            r"lv_obj_add_event_cb\s*\(\s*ui->(\w+)\.(\w+)\s*,\s*(\w+)\s*,", text
        ):
            reg_map[rm.group(3)] = (rm.group(1), rm.group(2))
        if from_screen not in screens:
            # still allow — may be typo; skip unknown
            if from_screen not in screens:
                pass

        text = path.read_text(encoding="utf-8", errors="replace")
        # Split into handler functions roughly
        for hm in re.finditer(
            r"static\s+void\s+(\w+)_event_handler\s*\([^)]*\)\s*\{(.*?)^\}",
            text,
            re.DOTALL | re.MULTILINE,
        ):
            handler_name = hm.group(1)  # btn_start or sometimes other
            body = hm.group(2)

            # Only care about CLICKED navigation
            if "LV_EVENT_CLICKED" not in body and "ui_" not in body:
                continue

            # Target: ui_<name>_screen_init or _ui_screen_change(&ui-><name>.root
            targets = []
            for tm in re.finditer(r"ui_(\w+)_screen_init\s*\(", body):
                targets.append(tm.group(1))
            for tm in re.finditer(r"_ui_screen_change\s*\(\s*&ui->(\w+)\.root", body):
                targets.append(tm.group(1))
            # unique preserve order
            uniq: list[str] = []
            for t in targets:
                if t not in uniq:
                    uniq.append(t)
            if not uniq:
                continue
            to_screen = uniq[0]

            # Button field: prefer the REAL widget from the registration map
            # (AIDOGUI may attach handlers to non btn_-named widgets / root);
            # cmd stays semantic (derived from the event handler name).
            btn_field = handler_name
            reg = reg_map.get(handler_name + "_event_handler") or reg_map.get(handler_name)
            if reg and reg[0] == from_screen:
                btn_field = reg[1]
            elif not btn_field.startswith("btn_"):
                btn_field = "btn_" + handler_name

            cmd = btn_to_cmd(handler_name if handler_name.startswith("btn_")
                             else "btn_" + handler_name)

            pol = policy_for(from_screen, to_screen)
            key = (from_screen, cmd, to_screen)
            if key not in seen_edge:
                seen_edge.add(key)
                edges.append(
                    Edge(
                        from_screen=from_screen,
                        cmd=cmd,
                        to_screen=to_screen,
                        policy=pol,
                        btn=btn_field,
                    )
                )
            bkey = (from_screen, btn_field, cmd)
            if bkey not in seen_bind:
                seen_bind.add(bkey)
                binds.append(Bind(screen=from_screen, btn=btn_field, cmd=cmd))

        # Also parse aido_event_init_<screen> registrations as fallback binds
        # lv_obj_add_event_cb(ui->menu.btn_start, btn_start_event_handler, ...)
        for rm in re.finditer(
            r"lv_obj_add_event_cb\s*\(\s*ui->(\w+)\.(btn_\w+)\s*,\s*(\w+)_event_handler",
            text,
        ):
            scr, btn, hname = rm.group(1), rm.group(2), rm.group(3)
            # Find if this handler has a target already captured
            matching = [e for e in edges if e.from_screen == scr and e.btn == btn]
            if matching:
                continue
            # Handler might use different naming — search handler body again
            # Already covered by handler scan if target exists.

    return edges, binds


def collect_cmds(edges: list[Edge], binds: list[Bind]) -> list[str]:
    cmds: list[str] = []
    for e in edges:
        if e.cmd not in cmds:
            cmds.append(e.cmd)
    for b in binds:
        if b.cmd not in cmds:
            cmds.append(b.cmd)
    return cmds


def normalize_i18n_calls(proj: Path, screens: list[str]) -> int:
    """AIDOGUI exports can keep stale i18n refresh calls for screens that no
    longer exist (e.g. cloning an older project). Comment out calls to
    ui_<X>_refresh_i18n() that are not declared in any project header.
    Idempotent: lines already marked with [import] are skipped.
    """
    i18n_c = proj / "i18n" / "ui_i18n.c"
    if not i18n_c.is_file():
        return 0
    declared: set[str] = set()
    for h in proj.rglob("*.h"):
        try:
            txt = h.read_text(encoding="utf-8", errors="replace")
        except OSError:
            continue
        for m in re.finditer(r"\b(ui_\w+_refresh_i18n)\s*\(", txt):
            declared.add(m.group(1))

    lines = i18n_c.read_text(encoding="utf-8", errors="replace").splitlines(keepends=True)
    changed = 0
    for i, line in enumerate(lines):
        if "[import]" in line:
            continue
        names = re.findall(r"\b(ui_\w+_refresh_i18n)\s*\(", line)
        stale = [n for n in names if n not in declared]
        if not stale:
            continue
        stripped = line.rstrip("\r\n")
        eol = line[len(stripped):]
        lines[i] = f"// [import] stale screen ref removed ({', '.join(stale)}): {stripped}{eol}"
        changed += 1
    if changed:
        i18n_c.write_text("".join(lines), encoding="utf-8")
        print(f"[gen_mvp] i18n: commented {changed} stale refresh_i18n call(s) in i18n/ui_i18n.c")
    return changed


