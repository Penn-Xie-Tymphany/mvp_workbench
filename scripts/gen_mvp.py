def scan_widget_info(proj: Path, screens: list[str]) -> dict[str, dict[str, dict]]:
    """Ground-truth widget inventory from the generated screen sources.

    Parses screens/ui_<screen>.c:
      aidogui_ui.<scr>.<name> = lv_<class>_create(parent)  → class + parent
      lv_label_set_text(aidogui_ui.<scr>.<name>, "...")    → initial text
      lv_obj_set_size/width/height/align/x/y               → layout (preview)
    This replaces name-prefix guessing — ANY label is bindable regardless
    of what AIDOGUI named it, and the page preview can be reconstructed.
    """
    out: dict[str, dict[str, dict]] = {s: {} for s in screens}
    for s in screens:
        f = proj / "screens" / f"ui_{s}.c"
        if not f.is_file():
            continue
        text = f.read_text(encoding="utf-8", errors="replace")
        for m in re.finditer(
            r"aidogui_ui\.(\w+)\.(\w+)\s*=\s*lv_(\w+)_create\s*\(\s*([^;\n]*?)\)",
            text,
        ):
            scr, name, cls, args = m.group(1), m.group(2), m.group(3), m.group(4)
            if scr not in out or name in out[scr]:
                continue
            parent = ""
            pm = re.search(r"aidogui_ui\.\w+\.(\w+)", args)
            if pm:
                parent = pm.group(1)
            out[scr][name] = {"cls": cls, "parent": parent}
        for m in re.finditer(
            r'lv_label_set_text\s*\(\s*aidogui_ui\.(\w+)\.(\w+)\s*,\s*"((?:[^"\\]|\\.)*)"\s*\)',
            text,
        ):
            scr, name, txt = m.group(1), m.group(2), m.group(3)
            if scr not in out:
                continue
            if name in out[scr]:
                out[scr][name]["text"] = txt
            else:
                out[scr][name] = {"cls": "label", "parent": "", "text": txt}
        for m in re.finditer(
            r"lv_obj_set_size\(aidogui_ui\.(\w+)\.(\w+),\s*(-?\d+),\s*(-?\d+)\)", text
        ):
            scr, name, w, h = m.groups()
            if scr in out and name in out[scr]:
                out[scr][name]["w"], out[scr][name]["h"] = int(w), int(h)
        for m in re.finditer(
            r"lv_obj_set_width\(aidogui_ui\.(\w+)\.(\w+),\s*"
            r"(LV_SIZE_CONTENT|lv_pct\((\d+)\)|(-?\d+))\)", text
        ):
            scr, name, raw, pct, intv = m.group(1), m.group(2), m.group(3), m.group(4), m.group(5)
            if scr in out and name in out[scr]:
                out[scr][name]["w"] = ("content" if raw == "LV_SIZE_CONTENT"
                                       else f"pct:{pct}" if pct is not None else int(intv))
        for m in re.finditer(
            r"lv_obj_set_height\(aidogui_ui\.(\w+)\.(\w+),\s*"
            r"(LV_SIZE_CONTENT|lv_pct\((\d+)\)|(-?\d+))\)", text
        ):
            scr, name, raw, pct, intv = m.group(1), m.group(2), m.group(3), m.group(4), m.group(5)
            if scr in out and name in out[scr]:
                out[scr][name]["h"] = ("content" if raw == "LV_SIZE_CONTENT"
                                       else f"pct:{pct}" if pct is not None else int(intv))
        for m in re.finditer(
            r"lv_obj_set_style_radius\(aidogui_ui\.(\w+)\.(\w+),\s*LV_RADIUS_CIRCLE", text
        ):
            scr, name = m.group(1), m.group(2)
            if scr in out and name in out[scr]:
                out[scr][name]["round"] = True
        for m in re.finditer(
            r"lv_obj_set_align\(aidogui_ui\.(\w+)\.(\w+),\s*LV_ALIGN_(\w+)\)", text
        ):
            scr, name, al = m.groups()
            if scr in out and name in out[scr]:
                out[scr][name]["align"] = al
        for m in re.finditer(
            r"lv_obj_set_x\(aidogui_ui\.(\w+)\.(\w+),\s*(-?\d+)\)", text
        ):
            scr, name, x = m.groups()
            if scr in out and name in out[scr]:
                out[scr][name]["x"] = int(x)
        for m in re.finditer(
            r"lv_obj_set_y\(aidogui_ui\.(\w+)\.(\w+),\s*(-?\d+)\)", text
        ):
            scr, name, y = m.groups()
            if scr in out and name in out[scr]:
                out[scr][name]["y"] = int(y)
        for m in re.finditer(
            r"lv_obj_align\(aidogui_ui\.(\w+)\.(\w+),\s*LV_ALIGN_(\w+),\s*(-?\d+),\s*(-?\d+)\)",
            text,
        ):
            scr, name, al, x, y = m.groups()
            if scr in out and name in out[scr]:
                out[scr][name]["align"] = al
                out[scr][name]["x"], out[scr][name]["y"] = int(x), int(y)
    return out


