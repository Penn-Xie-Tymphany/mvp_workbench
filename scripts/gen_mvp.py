_BTN_ALIASES = {
    "over": "DIE",  # Snake game-over button historically APP_CMD_DIE
    "menu": "HOME",  # pause.btn_menu → HOME
}


def _strip_c_comments(text: str) -> str:
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.DOTALL)
    text = re.sub(r"//.*?$", "", text, flags=re.MULTILINE)
    return text


def btn_to_cmd(btn_field: str) -> str:
    """btn_start → START; btn_dashboard → DASHBOARD; btn_over → DIE."""
    name = btn_field
    if name.startswith("btn_"):
        name = name[4:]
    key = name.lower()
    if key in _BTN_ALIASES:
        return _BTN_ALIASES[key]
    # wizard → WIZARD, devicea → DEVICEA, a0 → A0
    return re.sub(r"[^A-Za-z0-9]+", "_", name).upper()


def policy_for(from_s: str, to_s: str) -> str:
    # Heuristic: overlay pause on top of game → HIDE previous
    if to_s.lower() == "pause" and from_s.lower() in ("game", "play", "main"):
        return "HIDE"
    if "pause" in to_s.lower() and from_s.lower() != to_s.lower():
        # broader: any *pause* target from non-pause
        if from_s.lower() not in ("pause",):
            return "HIDE"
    return "DEL"


def scan_screens(ui_h: Path, screens_dir: Path) -> tuple[list[str], str]:
    screens: list[str] = []
    bootstrap = ""
    if ui_h.is_file():
        text = ui_h.read_text(encoding="utf-8", errors="replace")
        for m in re.finditer(r'#include\s+"screens/ui_(\w+)\.h"', text):
            name = m.group(1)
            if name not in screens:
                screens.append(name)
            if not bootstrap:
                bootstrap = name
    if not screens and screens_dir.is_dir():
        for p in sorted(screens_dir.glob("ui_*.h")):
            name = p.stem[3:] if p.stem.startswith("ui_") else p.stem
            screens.append(name)
        if screens:
            bootstrap = screens[0]
    return screens, bootstrap


def scan_buttons(objects_h: Path, screens: list[str]) -> dict[str, list[str]]:
    out: dict[str, list[str]] = {s: [] for s in screens}
    if not objects_h.is_file():
        return out
    text = objects_h.read_text(encoding="utf-8", errors="replace")
    # Match each aidogui_<screen>_objects_t struct
    for m in re.finditer(
        r"typedef\s+struct\s*\{(.*?)\}\s*aidogui_(\w+)_objects_t\s*;",
        text,
        re.DOTALL,
    ):
        body, screen = m.group(1), m.group(2)
        if screen not in out:
            out[screen] = []
        for bm in re.finditer(r"lv_obj_t\s*\*\s*(btn_\w+)\s*;", body):
            btn = bm.group(1)
            if btn not in out[screen]:
                out[screen].append(btn)
    return out


def scan_widgets(objects_h: Path, screens: list[str]) -> dict[str, list[str]]:
    """All lv_obj_t* widget fields per screen (for output/control binding)."""
    out: dict[str, list[str]] = {s: [] for s in screens}
    if not objects_h.is_file():
        return out
    text = objects_h.read_text(encoding="utf-8", errors="replace")
    for m in re.finditer(
        r"typedef\s+struct\s*\{(.*?)\}\s*aidogui_(\w+)_objects_t\s*;",
        text,
        re.DOTALL,
    ):
        body, screen = m.group(1), m.group(2)
        if screen not in out:
            out[screen] = []
        for wm in re.finditer(r"lv_obj_t\s*\*\s*(\w+)\s*;", body):
            w = wm.group(1)
            if w not in out[screen]:
                out[screen].append(w)
    return out


