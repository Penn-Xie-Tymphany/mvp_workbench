def write_custom_c(proj: Path, *, force: bool = False) -> bool:
    custom = proj / "custom" / "custom.c"
    custom.parent.mkdir(parents=True, exist_ok=True)
    if custom.is_file() and not force:
        txt = custom.read_text(encoding="utf-8", errors="replace")
        if "MVP_USER_BEGIN" in txt:
            return False
        if "presenter_init" in txt and "nav_bootstrap" in txt:
            # Already MVP-wired; stamp USER marker if missing by leaving as-is
            return False
    body = f"""#include "custom.h"
#include "../ui.h"
#include "view_bind.h"
#include "app_presenter.h"
#include "app_nav.h"

{USER_BEGIN}
/* AIDOGUI re-export should not wipe this file — import script restores it.
 * Boot MVP: model → nav bootstrap → bind presenter cmds (neutralize CHANGE_SCREEN). */
void custom_init(aidogui_ui_t * ui)
{{
    presenter_init();
    nav_bootstrap();
    view_bind(ui);
}}
{USER_END}
"""
    custom.write_text(body, encoding="utf-8")
    return True


def generate(proj: Path, *, force_user: bool = False, force_custom: bool = False,
             io_json: Path | None = None) -> ProjectScan:
    if not proj.is_dir():
        raise SystemExit(f"not a directory: {proj}")
    if not (proj / "ui.h").is_file():
        raise SystemExit(f"missing ui.h in {proj}")

    scan = scan_project(proj)
    if not scan.screens:
        raise SystemExit(f"no screens found in {proj}")

    normalize_i18n_calls(proj, scan.screens)
    sync_lv_conf_depth(proj)
    ensure_lvgl_version(proj)

    # --- io.json contract merge -------------------------------------------
    io_path = io_json or find_io_json(proj)
    io_data = None
    if io_path and io_path.is_file():
        try:
            io_data = json.loads(io_path.read_text(encoding="utf-8", errors="replace"))
            print(f"[gen_mvp] io contract: {io_path}")
        except (OSError, ValueError) as exc:
            print(f"[gen_mvp] WARN io contract unreadable ({exc})")
    if io_data:
        for c in _io_cmds(io_data):
            if c not in scan.cmds:
                scan.cmds.append(c)
        screen_set = {s.lower() for s in scan.screens}
        for f in io_data.get("flows", []):
            frm = str(f.get("from", "")).strip().lower()
            to = str(f.get("to", "")).strip().lower()
            cmd = _io_ident(f.get("on", "")).upper()
            if not (frm and to and cmd) or frm not in screen_set or to not in screen_set:
                continue
            param = str(f.get("param", "")).strip()  # "device=A"
            pkey = _io_ident(param.partition("=")[0]).lower()
            pval = param.partition("=")[2].strip()
            # contract flows OVERRIDE scanned edges with the same (from, cmd)
            match = next((e for e in scan.edges
                          if e.from_screen.lower() == frm and e.cmd == cmd), None)
            if match:
                match.to_screen = to
                match.policy = str(f.get("policy", match.policy))
                match.param_key = pkey
                match.param_val = pval
            else:
                scan.edges.append(Edge(frm, cmd, to,
                                       str(f.get("policy", "DEL")),
                                       param_key=pkey, param_val=pval))

    mvp = proj / "mvp"
    mvp.mkdir(parents=True, exist_ok=True)

    write_app_cmd_h(scan, mvp / "app_cmd.h")
    write_app_cmd_c(scan, mvp / "app_cmd.c")
    write_app_model_h(scan, mvp / "app_model.h")
    wrote_model = write_app_model_c(scan, mvp / "app_model.c", force=force_user)
    write_nav_table(scan, mvp / "app_nav_table.c")
    write_edges(scan, mvp / "app_edges.c")
    write_view_bind(scan, mvp / "view_bind.c")
    wrote_apply = write_view_apply(scan, mvp / "view_apply.c", force=force_user)
    write_meta(scan, mvp / "mvp_meta.json")
    write_transitions_csv(scan, mvp / "transitions.csv")
    wrote_custom = write_custom_c(proj, force=force_custom)

    if io_data:
        io_fields = _io_fields(io_data)
        # Always rewrite the managed section (even empty) so stale fields go away
        write_app_model_user_h(mvp / "app_model_user.h", io_fields)
        write_io_store(mvp, [f for f in io_fields if f.get("keyed")])
        if io_fields:
            write_app_io_table(mvp, io_fields)
            write_io_view(mvp, scan, io_fields, io_data.get("outputs", []))
            print(f"  io fields({len(io_fields)}): " + ", ".join(f["name"] for f in io_fields))
        else:
            _remove_io_table(mvp)
    else:
        _remove_io_table(mvp)

    print(f"[gen_mvp] project={scan.name}")
    print(f"  screens({len(scan.screens)}): {', '.join(scan.screens)}")
    print(f"  bootstrap: {scan.bootstrap}")
    print(f"  cmds({len(scan.cmds)}): {', '.join(scan.cmds)}")
    print(f"  edges: {len(scan.edges)}  binds: {len(scan.binds)}")
    print(f"  wrote mvp/ → {mvp}")
    print(f"  app_model.c: {'written' if wrote_model else 'kept (USER)'}")
    print(f"  view_apply.c: {'written' if wrote_apply else 'kept (USER)'}")
    print(f"  custom.c: {'written' if wrote_custom else 'kept'}")
    return scan


def main() -> None:
    ap = argparse.ArgumentParser(description="Generate MVP sources for an AIDOGUI project")
    ap.add_argument("project", type=Path, help="Path to ui_import/<Project>")
    ap.add_argument("--force-user", action="store_true", help="Overwrite USER files")
    ap.add_argument("--force-custom", action="store_true", help="Overwrite custom/custom.c")
    ap.add_argument("--io-json", type=Path, default=None, help="Explicit io.json contract path")
    args = ap.parse_args()
    generate(args.project.resolve(), force_user=args.force_user, force_custom=args.force_custom,
             io_json=args.io_json.resolve() if args.io_json else None)


if __name__ == "__main__":
    main()
