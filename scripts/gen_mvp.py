#!/usr/bin/env python3
"""Generate project-agnostic MVP sources from an AIDOGUI Export tree.

Usage:
  gen_mvp.py <ui_import/ProjectDir>
  gen_mvp.py /path/to/aidogui_mvp/ui_import/SnakeHandheld

Writes into <project>/mvp/:
  app_model.h/c, app_cmd.h/c, app_nav_table.c, app_edges.c,
  view_bind.c, view_apply.c, mvp_meta.json, transitions.csv
  and (if needed) rewrites custom/custom.c to bootstrap MVP.

Preserve policy:
  - Always overwrite: app_cmd.*, app_nav_table.c, app_edges.c, view_bind.c,
    app_model.h, mvp_meta.json, transitions.csv
  - Write once (keep if MVP_USER_BEGIN present): app_model.c, view_apply.c
  - custom/custom.c: write only if missing presenter_init/nav_bootstrap,
    or force with --force-custom
"""

