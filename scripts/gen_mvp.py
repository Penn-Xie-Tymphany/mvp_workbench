def _vt(ver: str) -> tuple[int, int, int]:
    try:
        parts = [int(x) for x in ver.strip().split(".")]
    except ValueError:
        return (0, 0, 0)
    while len(parts) < 3:
        parts.append(0)
    return tuple(parts[:3])


def detect_required_lvgl(proj: Path) -> tuple[int, int, int] | None:
    """Scan project sources for `#if !LV_VERSION_CHECK(m, n, p)` guards
    (AIDOGUI emits these for version-dependent features, e.g. font stride).
    Returns the highest required (major, minor, patch), or None."""
    best: tuple[int, int, int] | None = None
    files = list(proj.rglob("*.c")) + list(proj.rglob("*.h"))
    for f in files:
        try:
            txt = f.read_text(encoding="utf-8", errors="replace")
        except OSError:
            continue
        for m in re.finditer(r"!\s*LV_VERSION_CHECK\((\d+),\s*(\d+),\s*(\d+)\)", txt):
            v = (int(m.group(1)), int(m.group(2)), int(m.group(3)))
            if best is None or v > best:
                best = v
    return best


def current_lvgl_version(engine: Path) -> str:
    p = engine / "vendor" / "lvgl_active.txt"
    if p.is_file():
        return p.read_text(encoding="utf-8", errors="replace").strip()
    vhdr = engine / "vendor" / "lvgl" / "lv_version.h"
    if vhdr.is_file():
        txt = vhdr.read_text(encoding="utf-8", errors="replace")
        maj = re.search(r"LVGL_VERSION_MAJOR\s+(\d+)", txt)
        mnr = re.search(r"LVGL_VERSION_MINOR\s+(\d+)", txt)
        pat = re.search(r"LVGL_VERSION_PATCH\s+(\d+)", txt)
        if maj and mnr and pat:
            return f"{maj.group(1)}.{mnr.group(2)}.{pat.group(3)}"
    return "0.0.0"


def switch_lvgl(engine: Path, ver: str) -> bool:
    """Point the vendor/lvgl junction at vendor/lvgl_versions/<ver>."""
    src = engine / "vendor" / "lvgl_versions" / ver
    if not src.is_dir():
        return False
    link = engine / "vendor" / "lvgl"
    if link.exists() or link.is_symlink():
        os.rmdir(str(link))  # junction only — target untouched
    import _winapi
    _winapi.CreateJunction(str(src), str(link))
    (engine / "vendor" / "lvgl_active.txt").write_text(ver + "\n", encoding="ascii")
    print(f"[gen_mvp] LVGL switched: vendor/lvgl → {ver}")
    return True


def ensure_lvgl_version(proj: Path) -> str | None:
    """Make vendor/lvgl satisfy the project's minimum LVGL requirement.
    Auto-switches among installed versions; auto-fetches when missing."""
    engine = find_engine_root(proj)
    if not engine:
        return None
    req = detect_required_lvgl(proj)
    cur = current_lvgl_version(engine)
    if req and _vt(cur) >= req:
        return cur
    if req is None:
        return cur  # no constraint — keep whatever is active
    print(f"[gen_mvp] LVGL {cur} < required {req[0]}.{req[1]}.{req[2]} (by {proj.name})")
    vdir = engine / "vendor" / "lvgl_versions"
    installed = sorted((d.name for d in vdir.iterdir() if d.is_dir()), key=_vt) \
        if vdir.is_dir() else []
    cand = next((v for v in reversed(installed) if _vt(v) >= req), None)
    if cand:
        switch_lvgl(engine, cand)
        return cand
    # not installed → fetch via the standard script, then switch
    tag = f"v{req[0]}.{req[1]}.{req[2]}"
    fetch = Path(__file__).resolve().parent / "fetch_lvgl.ps1"
    print(f"[gen_mvp] {tag} not installed — fetching (git clone, may take minutes)...")
    try:
        subprocess.run(
            ["powershell", "-NoProfile", "-ExecutionPolicy", "Bypass",
             "-File", str(fetch), "-Tag", tag, "-Mode", "engine"],
            timeout=900,
        )
    except (OSError, subprocess.SubprocessError) as exc:
        print(f"[gen_mvp] WARN: auto-fetch failed ({exc}) — "
              f"run manually: scripts\\fetch_lvgl.ps1 -Tag {tag} -Mode engine")
        return cur
    if switch_lvgl(engine, f"{req[0]}.{req[1]}.{req[2]}"):
        return f"{req[0]}.{req[1]}.{req[2]}"
    return cur


def sync_lv_conf_depth(proj: Path) -> None:
    """AIDOGUI exports guard their color depth in ui.c (#error on mismatch).
    Follow the project: rewrite engine/lv_conf.h LV_COLOR_DEPTH when needed
    (per-project setting — e.g. lift6=16bit RGB565, ComplexHMI=32bit)."""
    ui_c = proj / "ui.c"
    if not ui_c.is_file():
        return
    m = re.search(r"#if\s*LV_COLOR_DEPTH\s*!=\s*(\d+)",
                  ui_c.read_text(encoding="utf-8", errors="replace"))
    if not m:
        return
    want = m.group(1)
    engine = find_engine_root(proj)
    if not engine:
        return
    conf = engine / "lv_conf.h"
    text = conf.read_text(encoding="utf-8", errors="replace")
    cm = re.search(r"#define\s+LV_COLOR_DEPTH\s+(\d+)", text)
    if not cm or cm.group(1) == want:
        return
    conf.write_text(text[:cm.start()] + f"#define LV_COLOR_DEPTH {want}" + text[cm.end():],
                    encoding="utf-8")
    print(f"[gen_mvp] lv_conf: LV_COLOR_DEPTH {cm.group(1)} → {want} "
          f"(跟随工程 {proj.name}) — 下次 Build 全量重编")


def _io_ident(s: str) -> str:
    return re.sub(r"[^A-Za-z0-9_]+", "_", str(s).strip()).strip("_")


def _default_ctype(kind: str) -> str:
    return "bool" if kind in ("button", "switch", "bool") else "float"


def _io_cmds(data: dict) -> list[str]:
    """CMD names referenced by input binds + user flows."""
    out: list[str] = []
    for inp in data.get("inputs", []):
        b = inp.get("bind") or {}
        if b.get("type") == "cmd":
            n = _io_ident(b.get("name", "")).upper()
            if n and n not in out:
                out.append(n)
    for f in data.get("flows", []):
        n = _io_ident(f.get("on", "")).upper()
        if n and n not in out:
            out.append(n)
    return out


def _io_fields(data: dict) -> list[dict]:
    """Model variables: contract 'fields' section first, then any bind
    references (auto-added with default ctype). Returns [{name,ctype,rw,init}]."""
    out: list[dict] = []
    seen: set[str] = set()

    def add(name: str, ctype: str, rw: str, init=0, keyed: str = "") -> None:
        name = _io_ident(name)
        if not name:
            return
        if name in seen:
            for e in out:
                if e["name"] == name:
                    if rw == "rw":
                        e["rw"] = "rw"
                    if e.get("init") in (None, 0) and init not in (None, 0):
                        e["init"] = init
            return
        seen.add(name)
        out.append({"name": name, "ctype": ctype or "float", "rw": rw,
                    "init": init, "keyed": keyed})

    for f in data.get("fields", []):
        add(f.get("name", ""), f.get("ctype", "float"), "decl",
            f.get("init", 0), f.get("keyed", ""))
    # param keys carried by flows → string model fields written by navigation
    for fl in data.get("flows", []):
        pk = _io_ident(str(fl.get("param", "")).partition("=")[0]).lower()
        if pk:
            add(pk, "string", "param")
    for inp in data.get("inputs", []):
        b = inp.get("bind") or {}
        if b.get("type") == "field":
            add(b.get("name", ""), b.get("ctype") or _default_ctype(str(inp.get("kind", ""))), "rw")
    for o in data.get("outputs", []):
        b = o.get("bind") or {}
        if b.get("type") == "field":
            add(b.get("name", ""), b.get("ctype") or _default_ctype(str(o.get("kind", ""))), "ro")
        elif b.get("type") == "widget":
            add(b.get("field", ""), b.get("ctype", "float"), "ro")
    return out


def write_io_store(mvp: Path, keyed_fields: list[dict]) -> None:
    """Tiny per-(field,key) KV store for parameterized data — e.g. rssi keyed
    by device: SET rssi@A "..." fills slot A; a shared detail page displays
    io_store_get("rssi", m->device) i.e. the entry chosen by navigation."""
    (mvp / "io_store.h").write_text(
        f"""{GEN_BANNER}
#ifndef IO_STORE_H
#define IO_STORE_H

#include <stdbool.h>

#ifdef __cplusplus
extern "C" {{
#endif

void io_store_put(const char * field, const char * key, const char * val);
const char * io_store_get(const char * field, const char * key);

#ifdef __cplusplus
}}
#endif
#endif
""",
        encoding="utf-8",
    )
    names = ", ".join(f["name"] for f in keyed_fields)
    (mvp / "io_store.c").write_text(
        f"""{GEN_BANNER}
/* Keyed data slots for: {names} */
#include "io_store.h"

#include <string.h>
#include <stdio.h>

#define IO_STORE_SLOTS 32

typedef struct {{
    char field[24];
    char key[24];
    char val[96];
}} io_slot_t;

static io_slot_t g_store[IO_STORE_SLOTS];

static io_slot_t * find_slot(const char * field, const char * key, bool create)
{{
    io_slot_t * free_slot = NULL;
    for (int i = 0; i < IO_STORE_SLOTS; ++i) {{
        io_slot_t * s = &g_store[i];
        if (!s->field[0]) {{
            if (!free_slot) free_slot = s;
            continue;
        }}
        if (strcmp(s->field, field) == 0 && strcmp(s->key, key) == 0) return s;
    }}
    if (!create) return NULL;
    if (free_slot) return free_slot;
    return NULL; /* store full */
}}

void io_store_put(const char * field, const char * key, const char * val)
{{
    if (!field || !field[0] || !key || !key[0]) return;
    io_slot_t * s = find_slot(field, key, true);
    if (!s) return;
    snprintf(s->field, sizeof(s->field), "%s", field);
    snprintf(s->key, sizeof(s->key), "%s", key);
    snprintf(s->val, sizeof(s->val), "%s", val ? val : "");
}}

const char * io_store_get(const char * field, const char * key)
{{
    if (!field || !field[0] || !key || !key[0]) return "";
    io_slot_t * s = find_slot(field, key, false);
    return s ? s->val : "";
}}
""",
        encoding="utf-8",
    )
    print(f"[gen_mvp] io_store: keyed slots for {names}")


def write_io_view(mvp: Path, scan: "ProjectScan", fields: list[dict],
                  outputs: list[dict]) -> None:
    """Generated widget auto-apply: output nodes bound to a screen widget get
    their model value written on every presenter tick (labels only — the
    objects struct carries plain lv_obj_t*, so only lbl_/label_ widgets are
    safe to auto-write)."""
    decls = []
    keyed_used = False
    for o in outputs:
        b = o.get("bind") or {}
        if b.get("type") != "widget":
            continue
        screen = str(b.get("screen", "")).lower()
        widget = str(b.get("widget", ""))
        field = _io_ident(b.get("field", ""))
        fe = next((f for f in fields if f["name"] == field), None)
        if not fe or screen not in scan.screens or not widget:
            continue
        info = (scan.widget_info.get(screen) or {}).get(widget) or {}
        cls = info.get("cls", "")
        forced = bool(b.get("force"))
        is_label = cls == "label" or (not cls and (
            widget.startswith(("lbl_", "label_")) or forced))
        is_value_w = cls in ("bar", "arc", "slider") and fe["ctype"] in ("int", "float")
        if not is_label and not is_value_w and not forced:
            kind_cn = {"label": "标签"}.get(cls, cls or "未知")
            print(f"[gen_mvp] io_view: skip {screen}.{widget} "
                  f"(class={kind_cn}; use bind.force=true to override)")
            continue
        prefix = str(b.get("prefix", ""))
        guard = (f"    if (ui->{screen}.root && lv_obj_is_valid(ui->{screen}.root)) {{\n")
        if is_value_w:
            fmt = "%d" if fe["ctype"] == "int" else "%.2f"
            cast = "(int32_t)" if fe["ctype"] == "int" else "(int32_t)"
            expr = f"{cast}m->{field}"
            fn = {"bar": "lv_bar_set_value", "arc": "lv_arc_set_value",
                  "slider": "lv_slider_set_value"}[cls]
            decls.append(guard +
                         f"        {fn}(ui->{screen}.{widget}, {expr}, LV_ANIM_OFF);\n    }}")
            continue
        if fe.get("keyed"):
            keyed_used = True
            vexp = f'io_store_get("{field}", m->{fe["keyed"]})'
            if prefix:
                decls.append(guard +
                             f'        lv_label_set_text_fmt(ui->{screen}.{widget}, '
                             f'"{prefix}%s", {vexp});\n    }}')
            else:
                decls.append(guard +
                             f"        lv_label_set_text(ui->{screen}.{widget}, {vexp});\n    }}")
            continue
        if fe["ctype"] == "string":
            if prefix:
                decls.append(guard +
                             f'        lv_label_set_text_fmt(ui->{screen}.{widget}, '
                             f'"{prefix}%s", m->{field});\n    }}')
            else:
                decls.append(guard +
                             f"        lv_label_set_text(ui->{screen}.{widget}, m->{field});\n    }}")
            continue
        fmt = {"int": "%d", "float": "%.2f", "bool": "%d"}.get(fe["ctype"], "%.2f")
        cast = {"int": "(int)", "float": "(double)", "bool": "(int)"}.get(fe["ctype"], "(double)")
        if fe["ctype"] == "bool":
            expr = f"m->{field} ? 1 : 0"
        else:
            expr = f"{cast}m->{field}"
        decls.append(guard +
                     f'        lv_label_set_text_fmt(ui->{screen}.{widget}, '
                     f'"{prefix}{fmt}", {expr});\n    }}'
                     )
    (mvp / "io_view.h").write_text(
        f"""{GEN_BANNER}
#ifndef IO_VIEW_H
#define IO_VIEW_H

#include "ui.h"
#include "app_model.h"

#ifdef __cplusplus
extern "C" {{
#endif

void io_view_apply(aidogui_ui_t * ui, const app_model_t * m);

#ifdef __cplusplus
}}
#endif
#endif
""",
        encoding="utf-8",
    )
    body = "\n".join(decls) if decls else "    (void)ui; (void)m;"
    (mvp / "io_view.c").write_text(
        f"""{GEN_BANNER}
#include "io_view.h"
{'#include "io_store.h"' if keyed_used else ''}
void io_view_apply(aidogui_ui_t * ui, const app_model_t * m)
{{
    if (!ui || !m) return;
{body}
}}
""",
        encoding="utf-8",
    )
    if decls:
        print(f"[gen_mvp] io_view: {len(decls)} widget binding(s) generated")


