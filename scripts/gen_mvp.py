def write_app_model_c(scan: ProjectScan, dest: Path, *, force: bool = False) -> bool:
    if dest.is_file() and _has_user_block(dest) and not force:
        return False
    boot = screen_enum(scan.bootstrap)
    name_cases = "\n".join(
        f'        case {screen_enum(s)}: return "{s.upper()}";' for s in scan.screens
    )
    from_cases = "\n".join(
        f'    if (!strcasecmp(name, "{s.upper()}")) return {screen_enum(s)};'
        for s in scan.screens
    )
    body = f"""{GEN_BANNER}
#include "app_model.h"
#include <string.h>
#include <strings.h>

static app_model_t g_model;

void app_model_init(app_model_t * m)
{{
    if (!m) m = &g_model;
    memset(m, 0, sizeof(*m));
    m->screen = {boot};
    if (m != &g_model) g_model = *m;
}}

app_model_t * app_model_get(void)
{{
    return &g_model;
}}

const char * app_screen_name(app_screen_id_t id)
{{
    switch (id) {{
{name_cases}
        default: return "NONE";
    }}
}}

app_screen_id_t app_screen_from_name(const char * name)
{{
    if (!name) return APP_SCREEN_NONE;
{from_cases}
    return APP_SCREEN_NONE;
}}

{USER_BEGIN}
/* Edit model side-effects here. Regenerator will NOT overwrite this file
 * once MVP_USER_BEGIN is present. */
void model_on_cmd(app_model_t * m, app_cmd_t cmd,
                  app_screen_id_t from, app_screen_id_t to)
{{
    (void)m; (void)cmd; (void)from; (void)to;
}}
{USER_END}
"""
    dest.write_text(body, encoding="utf-8")
    return True


