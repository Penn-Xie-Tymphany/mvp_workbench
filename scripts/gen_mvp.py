def find_io_json(proj: Path) -> Path | None:
    """Locate projects/<name>/io.json by walking up from ui_import/<name>."""
    for parent in proj.parents:
        cand = parent / "projects" / proj.name / "io.json"
        if cand.is_file():
            return cand
    return None


def find_engine_root(proj: Path) -> Path | None:
    for parent in proj.parents:
        if (parent / "lv_conf.h").is_file():
            return parent
    return None


